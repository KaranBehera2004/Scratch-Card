export function workspaceTranslator(language = "en") {
  const index = { hi: 0, te: 1 }[language];
  return function translate(text, values = {}) {
    const limit = typeof text === "string" && text.match(/^(card|branch|account) limit reached \((\d+)\)\. Contact your administrator\.$/);
    if (limit) return translate("{resource} limit reached ({maximum}). Contact your administrator.", {
      resource: translate(limit[1]), maximum: limit[2],
    });
    const translated = copy[text]?.[index] || text;
    return typeof translated === "string" ? translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match) : translated;
  };
}

export const WorkspaceLocale = createContext(workspaceTranslator());
export const useWorkspaceText = () => useContext(WorkspaceLocale);
